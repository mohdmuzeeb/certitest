"""S2: service-level case study (multi-account ledger with 20 requirements, 30 seeded faults)."""
from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))

from certitest import sandbox  # noqa: E402
from certitest.model import Candidate, Requirement, Task  # noqa: E402

from .faults import FAULTS, apply  # noqa: E402

INTERFACE = '''class LedgerError(Exception): ...
class AccountExists(LedgerError): ...
class AccountNotFound(LedgerError): ...
class InvalidAmount(LedgerError): ...
class InsufficientFunds(LedgerError): ...
class CurrencyMismatch(LedgerError): ...
class IdempotencyConflict(LedgerError): ...
class LimitExceeded(LedgerError): ...
class AccountFrozen(LedgerError): ...
class AccountNotEmpty(LedgerError): ...

class Ledger:
    def __init__(self) -> None: ...
    def open_account(self, account_id: str, currency: str) -> None: ...
    def close_account(self, account_id: str) -> None: ...
    def freeze(self, account_id: str) -> None: ...
    def unfreeze(self, account_id: str) -> None: ...
    def set_day(self, day: int) -> None: ...
    def deposit(self, account_id: str, amount: int) -> None: ...
    def withdraw(self, account_id: str, amount: int) -> None: ...
    def transfer(self, src: str, dst: str, amount: int, idempotency_key: str) -> str: ...
    def balance(self, account_id: str) -> int: ...
    def history(self, account_id: str) -> list[tuple[str, int, str | None]]: ...
    def total_balance(self, currency: str) -> int: ...
'''


def task() -> Task:
    text = (HERE / "REQUIREMENTS.md").read_text()
    reqs = [Requirement(m.group(1), m.group(2).strip()) for m in re.finditer(r"^- (R\d+): (.+)$", text, re.M)]
    preamble = text.split("\n- R1:")[0].replace("# Ledger service: functional requirements", "").strip()
    return Task(subject="s2", task_id="ledger", module_name="ledger", entry_point="Ledger", spec=preamble, interface=INTERFACE,
                requirements=reqs)


def reference() -> str:
    return (HERE / "ledger.py").read_text()


def candidates() -> list[Candidate]:
    ref = reference()
    out = [Candidate("reference", "ledger", ref, "correct", "canonical")]
    for fid in FAULTS:
        out.append(Candidate(fid, "ledger", apply(ref, fid), "faulty", "seeded", {"requirement": fid.split("-")[1]}))
    return out


def oracle(source: str) -> dict:
    res = sandbox.run_pytest({"ledger.py": source, "test_oracle.py": (HERE / "oracle_tests.py").read_text()}, test_file="test_oracle.py")
    return {"collected": res.collected, "failing": res.failing, "correct": res.collected and not res.failing and bool(res.outcomes)}
